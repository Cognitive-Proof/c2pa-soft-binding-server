// The manifest is a sidecar for this tiny SVG; the asset itself is never uploaded.
const ASSET = Buffer.from(
  '<svg xmlns="http://www.w3.org/2000/svg" width="10" height="10">' +
    '<rect width="10" height="10" fill="grey"/></svg>',
);

async function signTestManifest(title) {
  const signed = await signAssetSidecar({
    format: 'image/svg+xml',
    asset: ASSET,
    manifestDefinition: {
      claim_generator_info: [{ name: 'softbinding-api-conformance' }],
      title,
      assertions: [
        {
          label: 'c2pa.actions',
          data: {
            actions: [
              {
                action: 'c2pa.created',
                digitalSourceType: 'http://cv.iptc.org/newscodes/digitalsourcetype/digitalCreation',
              },
            ],
          },
        },
      ],
    },
    signcert: SIGNCERT,
    pkey: PKEY,
    alg: 'es256',
  });
  return Buffer.from(signed.manifest);
}

const title = process.argv[2];
if (!title) {
  console.error('Usage: node sign-manifest.mjs <title>');
  process.exit(1);
}
process.stdout.write((await signTestManifest(title)).toString('base64'));
